# =============================================================================
# Настройки RAG-пайплайна. Всё, что имеет смысл «покрутить», собрано здесь.
# =============================================================================
from dataclasses import dataclass
from pathlib import Path

# Папка RAG/ — от неё считаются пути к данным и к файлам базы.
RAG_DIR = Path(__file__).resolve().parent


# Все параметры пайплайна. dataclass сам создаёт конструктор со значениями
# по умолчанию, поэтому в тестах можно написать RAGConfig(qdrant_path=None, top_k=2).
@dataclass
class RAGConfig:
    # --- Данные ---------------------------------------------------------------
    # Markdown-документы базы знаний магазина (возвраты, доставка, гарантия...).
    knowledge_base_dir: Path = RAG_DIR / "data" / "knowledge_base"
    # Каталог товаров в JSON — каждый товар станет отдельным документом.
    products_path: Path = RAG_DIR / "data" / "products.json"

    # --- Векторная база (Qdrant) ---------------------------------------------
    # Папка, где Qdrant в локальном режиме хранит данные. None — база в памяти (для тестов).
    qdrant_path: Path | None = RAG_DIR / "qdrant_data"
    # Коллекция — аналог таблицы в обычной БД.
    collection_name: str = "shop_knowledge"

    # --- Эмбеддинги -----------------------------------------------------------
    # Маленькая (~90 МБ) быстрая английская модель; вектор из 384 чисел.
    embedding_model: str = "sentence-transformers/all-MiniLM-L6-v2"

    # --- Чанкинг --------------------------------------------------------------
    # Максимальная длина чанка в символах (без «шапки» с названием документа).
    chunk_size: int = 500
    # Сколько символов конца чанка повторяется в начале следующего.
    chunk_overlap: int = 100

    # --- Поиск ----------------------------------------------------------------
    # Сколько чанков доставать на один вопрос.
    top_k: int = 4
    # Чанки с похожестью (косинусом) ниже порога считаем нерелевантными.
    min_score: float = 0.3

    # --- Генерация ------------------------------------------------------------
    # "mock" — имитация без сети и ключей, "claude" — настоящая модель через Anthropic API.
    llm: str = "mock"
    claude_model: str = "claude-opus-5-5"
    # Насколько глубоко модель думает: low | medium | high | xhigh | max.
    # Для ответов по готовому контексту хватает low — быстрее и дешевле.
    claude_effort: str = "low"
